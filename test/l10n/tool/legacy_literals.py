"""Writes test/l10n/baseline/legacy_literals.json: every string literal in
lib/**/*.dart, with the language branch it is shown in.

Run from the repository root at the baseline commit:

    python3 test/l10n/tool/legacy_literals.py <commit>

The inventory is a record of that commit and is never regenerated by a
ticket that moves text. Branch rules, innermost first:

- `isSpanish ? A : B` (also `widget.isSpanish`, `_isSpanish`, and
  `_language == WelcomeLanguage.spanish`): literals in A are `es`, in B `en`;
- a call of a screen's `t(english, spanish)` or `_t(english, spanish)`
  helper: the first argument is `en`, the second `es`;
- `if (isSpanish) X` (or `if (!isSpanish) X`): X is `es` (`en`); its `else`,
  or when there is none the rest of the enclosing block, is the other one;
- a `const english` / `const spanish` list or string, or a constant named
  `*English` / `*Spanish` (such as `unavailableSpanish`): `en` / `es`;

Literals inside `${...}` interpolations are scanned too, with the same
rules, so `'${isSpanish ? 'a' : 'b'}'` tags `a` es and `b` en.
- anything else is `none` (shown in every language, or not shown).

Flags: `interpolated` (has `$`), `joined` (adjacent to the previous literal,
so Dart concatenates them), `key` (a widget key), `match` (a `case` or
`==` value: compared, not shown) and `directive` (import/export/part).

Generated files (`*.g.dart`, `lib/l10n/app_localizations*.dart`) are
skipped.
"""
import json, os, re, sys

COND = re.compile(r'(?:\bwidget\.|\b_|\b)isSpanish\s*\?(?![?.\[])|_language\s*==\s*WelcomeLanguage\.spanish\s*\?(?![?.\[])')
IF = re.compile(r'\bif\s*\(\s*(!?)\s*(?:widget\.|_)?isSpanish\s*\)')
# A helper whose parameters include `String english` and `String spanish`
# (`t(english, spanish)`, `localized(isSpanish, english, spanish)`).
HELPER_DEF = re.compile(r'String\s+(\w+)\s*\(([^)]*\bString\s+english\b[^)]*)\)')
HELPERS = {}  # name -> (english arg index, spanish arg index), from every file


def find_helpers(src):
    for d in HELPER_DEF.finditer(src):
        params = [p.strip().split()[-1] for p in d.group(2).split(',') if p.strip()]
        if 'english' in params and 'spanish' in params:
            HELPERS[d.group(1)] = (params.index('english'), params.index('spanish'))
TABLE = re.compile(r'\b(?:const|final)\s+(?:String\s+|List<String>\s+)?(english|spanish|\w*English|\w*Spanish)\s*=')


def scan(src):
    """String literals [(start, end, content, interpolated)] and a copy of
    `src` with comments and literal bodies blanked (same offsets)."""
    lits, out = [], list(src)
    i, n = 0, len(src)

    def blank(a, b, keep_newlines=True):
        for k in range(a, b):
            if not (keep_newlines and src[k] == '\n'): out[k] = ' '

    def string(i):
        raw = False
        start = i
        if src[i] in 'rR':
            raw = True
            i += 1
        q = src[i]
        triple = src.startswith(q * 3, i)
        delim = q * 3 if triple else q
        i += len(delim)
        body_start = i
        interp = False
        code = []  # ${...} regions: kept in the masked text, so a ternary in them is seen
        while i < n:
            if not raw and src[i] == '\\':
                i += 2
                continue
            if src.startswith(delim, i):
                lits.append((start, i + len(delim), src[body_start:i], interp))
                pos = body_start
                for a, b in code:
                    blank(pos, a)
                    pos = b
                blank(pos, i)
                return i + len(delim)
            if not raw and src[i] == '$':
                interp = True
                if i + 1 < n and src[i + 1] == '{':
                    depth, j = 1, i + 2
                    while j < n and depth:
                        c = src[j]
                        if c in '\'"' or (c in 'rR' and j + 1 < n and src[j + 1] in '\'"' and not (src[j - 1].isalnum() or src[j - 1] == '_')):
                            j = string(j)
                            continue
                        if c == '{': depth += 1
                        elif c == '}': depth -= 1
                        j += 1
                    code.append((i + 2, j - 1))
                    i = j
                    continue
            if not triple and src[i] == '\n':
                raise ValueError(f'unterminated string at {start}')
            i += 1
        raise ValueError(f'unterminated string at {start}')

    while i < n:
        c = src[i]
        if src.startswith('//', i):
            j = src.find('\n', i)
            j = n if j < 0 else j
            blank(i, j)
            i = j
        elif src.startswith('/*', i):
            j = src.find('*/', i) + 2
            blank(i, j)
            i = j
        elif c in '\'"' or (c in 'rR' and i + 1 < n and src[i + 1] in '\'"' and not (i and (src[i - 1].isalnum() or src[i - 1] == '_'))):
            i = string(i)
        else:
            i += 1
    return sorted(lits), ''.join(out)


OPEN, CLOSE = '([{', ')]}'


def expr_end(m, i, stop=',;)]}'):
    """End of the expression starting at `i` in masked text `m`."""
    depth, q = 0, 0
    while i < len(m):
        c = m[i]
        if c in OPEN: depth += 1
        elif c in CLOSE:
            if depth == 0: return i
            depth -= 1
        elif depth == 0 and c in stop: return i
        i += 1
    return i


def then_end(m, i):
    """End of the `A` of a ternary whose `?` is just before `i`."""
    depth, q = 0, 0
    while i < len(m):
        c = m[i]
        if c in OPEN: depth += 1
        elif c in CLOSE:
            if depth == 0: return i
            depth -= 1
        elif depth == 0 and c == '?' and m[i + 1:i + 2] not in ('?', '.', '['):
            q += 1
        elif depth == 0 and c == ':':
            if q == 0: return i
            q -= 1
        i += 1
    return i


def block_end(m, i):
    """`i` at '{': index after the matching '}'."""
    depth = 0
    while i < len(m):
        if m[i] == '{': depth += 1
        elif m[i] == '}':
            depth -= 1
            if depth == 0: return i + 1
        i += 1
    return i


def statement_end(m, i):
    j = i
    while j < len(m) and m[j].isspace(): j += 1
    if j < len(m) and m[j] == '{': return block_end(m, j)
    return expr_end(m, j, ';') + 1


def enclosing_block_end(m, i):
    depth = 0
    while i < len(m):
        if m[i] == '{': depth += 1
        elif m[i] == '}':
            if depth == 0: return i
            depth -= 1
        i += 1
    return i


def spans(m):
    """[(start, end, branch)] of every language branch in masked text `m`."""
    out = []
    for c in COND.finditer(m):
        a = c.end()
        a_end = then_end(m, a)
        b_end = expr_end(m, a_end + 1)
        out += [(a, a_end, 'es'), (a_end + 1, b_end, 'en')]
    for h, (ei, si) in HELPERS.items():
        for call in re.finditer(r'(?<![\w.])' + re.escape(h) + r'\s*\(', m):
            if m[max(0, call.start() - 7):call.start()].strip() == 'String':
                continue  # the definition
            args, pos = [], call.end()
            while pos < len(m):
                end = expr_end(m, pos)
                args.append((pos, end))
                if end >= len(m) or m[end] != ',': break
                pos = end + 1
            if len(args) > max(ei, si):
                out += [(args[ei][0], args[ei][1], 'en'), (args[si][0], args[si][1], 'es')]
    for f in IF.finditer(m):
        first = 'en' if f.group(1) else 'es'
        other = 'es' if first == 'en' else 'en'
        s_end = statement_end(m, f.end())
        out.append((f.end(), s_end, first))
        rest = re.match(r'\s*else\b', m[s_end:])
        if rest:
            e_start = s_end + rest.end()
            out.append((e_start, statement_end(m, e_start), other))
        else:
            out.append((s_end, enclosing_block_end(m, s_end), other))
    for t in TABLE.finditer(m):
        out.append((t.end(), expr_end(m, t.end(), ';'), 'en' if t.group(1).lower().endswith('english') else 'es'))
    return out


def inventory(path):
    src = open(path, encoding='utf-8').read()
    lits, masked = scan(src)
    sp = spans(masked)
    rows, prev_end = [], None
    for start, end, content, interp in lits:
        inner = [s for s in sp if s[0] <= start and end <= s[1]]
        branch = min(inner, key=lambda s: s[1] - s[0])[2] if inner else 'none'
        before = masked[max(0, start - 12):start]
        row = {'line': src.count('\n', 0, start) + 1, 'branch': branch, 'text': content}
        if interp: row['interpolated'] = True
        if re.search(r'(Value)?Key\(\s*$', before): row['key'] = True
        if re.search(r'(\bcase|==|!=)\s*$', before): row['match'] = True  # compared, not shown
        if prev_end is not None and masked[prev_end:start].strip() == '': row['joined'] = True
        if re.match(r'^\s*(import|export|part)\b', src[src.rfind('\n', 0, start) + 1:start]): row['directive'] = True
        rows.append(row)
        prev_end = end
    return rows


def main():
    commit = sys.argv[1]
    for root, _, names in os.walk('lib'):
        for name in names:
            if name.endswith('.dart'):
                find_helpers(scan(open(os.path.join(root, name), encoding='utf-8').read())[1])
    files = {}
    for root, _, names in os.walk('lib'):
        for name in sorted(names):
            path = os.path.join(root, name).replace(os.sep, '/')
            if not name.endswith('.dart') or name.endswith('.g.dart') or path.startswith('lib/l10n/app_localizations'):
                continue
            files[path] = inventory(path)
    files = dict(sorted(files.items()))
    counts = {b: sum(1 for rows in files.values() for r in rows if r['branch'] == b) for b in ('en', 'es', 'none')}
    out = {'baseCommit': commit,
           'about': 'Every string literal in lib/ at baseCommit, with the language branch it is shown in (test/l10n/tool/legacy_literals.py). Never regenerated by a ticket that moves text.',
           'counts': counts, 'files': files}
    os.makedirs('test/l10n/baseline', exist_ok=True)
    with open('test/l10n/baseline/legacy_literals.json', 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(json.dumps(out, indent=1, ensure_ascii=False) + '\n')
    print(counts, sum(len(v) for v in files.values()), 'literals in', len(files), 'files')


if __name__ == '__main__':
    main()
