import { normalisePhone } from "./phone";

describe("normalisePhone", () => {
  it.each([
    ["(555) 010-2244", "+15550102244"],
    ["555.010.4421", "+15550104421"],
    ["555 010 4421", "+15550104421"],
    ["1 555 010 4421", "+15550104421"],
    ["+1 (555) 010-2244", "+15550102244"],
    ["+44 20 7946 0958", "+442079460958"],
    ["  5550102244  ", "+15550102244"],
  ])("%p → %p", (input, expected) => {
    expect(normalisePhone(input)).toBe(expected);
  });

  it.each([
    "",
    "   ",
    "555-0102",
    "010-2244",
    "2 555 010 4421",
    "+0 555 010 4421",
    "+1 555",
    "555-010-2244 ext 3",
    "call me",
    "+1555010224412345678",
    "５５５０１０２２４４",
    "+".repeat(40),
  ])("%p → null", (input) => {
    expect(normalisePhone(input)).toBeNull();
  });
});
